import 'package:flutter/services.dart';

/// RDP 키보드 스캔코드(세트 1)와 확장(E0) 여부.
class RdpScancode {
  const RdpScancode(this.code, {this.extended = false});
  final int code;
  final bool extended;

  static const enter = RdpScancode(0x1C);
  static const backspace = RdpScancode(0x0E);
}

/// Flutter의 물리 키(USB HID 코드)를 RDP 스캔코드로 바꿉니다. 모르는 키는 null.
///
/// 물리 키 기준이므로 자판 배열과 한글 조합은 원격 서버의 입력기가 처리합니다.
RdpScancode? rdpScancodeFor(PhysicalKeyboardKey key) {
  final usage = key.usbHidUsage;
  if (usage >> 16 != 0x07) return null; // 키보드 페이지만
  return _hidToScancode[usage & 0xFFFF];
}

